CREATE TABLE transfers (
  transfer_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  reference_number VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  request_id BIGINT UNSIGNED NOT NULL UNIQUE,
  source_account_id BIGINT UNSIGNED NOT NULL,
  destination_account_id BIGINT UNSIGNED NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  transfer_status VARCHAR(16) NOT NULL DEFAULT 'completed',
  description VARCHAR(500) NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_transfer_request FOREIGN KEY (request_id) REFERENCES operation_requests(request_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transfer_source FOREIGN KEY (source_account_id) REFERENCES accounts(account_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transfer_destination FOREIGN KEY (destination_account_id) REFERENCES accounts(account_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transfer_creator FOREIGN KEY (created_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_transfer_accounts CHECK (source_account_id <> destination_account_id),
  CONSTRAINT ck_transfer_amount CHECK (amount > 0),
  CONSTRAINT ck_transfer_status CHECK (transfer_status = 'completed')
) ENGINE=InnoDB;
