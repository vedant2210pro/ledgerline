CREATE TABLE operation_requests (
  request_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  actor_id BIGINT UNSIGNED NOT NULL,
  operation VARCHAR(24) NOT NULL,
  idempotency_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_hash BINARY(32) NOT NULL,
  request_status VARCHAR(16) NOT NULL DEFAULT 'pending',
  result_reference VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  completed_at DATETIME(6) NULL,
  CONSTRAINT uq_operation_key UNIQUE (actor_id,operation,idempotency_key),
  CONSTRAINT fk_request_actor FOREIGN KEY (actor_id) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_operation_type CHECK (operation IN ('deposit','withdrawal','transfer','payroll','reversal')),
  CONSTRAINT ck_operation_key CHECK (CHAR_LENGTH(TRIM(idempotency_key)) > 0),
  CONSTRAINT ck_request_status CHECK (request_status IN ('pending','completed')),
  CONSTRAINT ck_request_completion CHECK ((request_status = 'pending' AND completed_at IS NULL AND result_reference IS NULL) OR (request_status = 'completed' AND completed_at IS NOT NULL AND result_reference IS NOT NULL))
) ENGINE=InnoDB;
