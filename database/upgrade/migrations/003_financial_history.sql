CREATE TABLE banking_transactions (
  transaction_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT UNSIGNED NOT NULL,
  branch_id BIGINT UNSIGNED NOT NULL,
  request_id BIGINT UNSIGNED NOT NULL,
  transfer_id BIGINT UNSIGNED NULL,
  transaction_type VARCHAR(24) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  balance_after DECIMAL(18,2) NOT NULL,
  transaction_date DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  description VARCHAR(500) NOT NULL,
  reference_number VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  transaction_status VARCHAR(16) NOT NULL DEFAULT 'completed',
  created_by BIGINT UNSIGNED NOT NULL,
  reversal_of_transaction_id BIGINT UNSIGNED NULL UNIQUE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_request_account UNIQUE (request_id,account_id),
  CONSTRAINT fk_transaction_account FOREIGN KEY (account_id) REFERENCES accounts(account_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transaction_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transaction_request FOREIGN KEY (request_id) REFERENCES operation_requests(request_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transaction_transfer FOREIGN KEY (transfer_id) REFERENCES transfers(transfer_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transaction_creator FOREIGN KEY (created_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_transaction_reversal FOREIGN KEY (reversal_of_transaction_id) REFERENCES banking_transactions(transaction_id) ON DELETE RESTRICT,
  CONSTRAINT ck_transaction_amount CHECK (amount > 0 AND balance_after >= 0),
  CONSTRAINT ck_transaction_type CHECK (transaction_type IN ('deposit','withdrawal','transfer_debit','transfer_credit','reversal_debit','reversal_credit')),
  CONSTRAINT ck_transaction_status CHECK (transaction_status = 'completed'),
  CONSTRAINT ck_transaction_transfer CHECK ((transaction_type IN ('transfer_debit','transfer_credit') AND transfer_id IS NOT NULL) OR (transaction_type NOT IN ('transfer_debit','transfer_credit') AND transfer_id IS NULL)),
  CONSTRAINT ck_transaction_reversal CHECK ((transaction_type IN ('reversal_debit','reversal_credit') AND reversal_of_transaction_id IS NOT NULL) OR (transaction_type NOT IN ('reversal_debit','reversal_credit') AND reversal_of_transaction_id IS NULL))
) ENGINE=InnoDB;